        /// <summary>
        /// Дополнительные образцы для замаскированных слов, у которых нет одной
        /// хорошей замены: "х*й" сравнивается с "хуй", "*бать" — с "ебать".
        /// </summary>
        public static readonly IReadOnlyList<string> MaskTargets = new[]
        {
            "хуй", "хуя", "хуе", "хуи", "хую", "пизд", "пиздюк", "ебал", "ебан", "ебут", "ебет", "ебу",
            "блят", "сук", "пидр", "мудак", "залупа", "манда", "шлюха", "гандон", "дрочить", "жопа",
