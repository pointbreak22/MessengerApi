            new Regex("porn|blowjob|handjob|^cum(?:shot)?$|^penis|^vagina|^dildo|^boobs?$|^tits?$|^titties|^horny$|^sex(?:y)?$", Opts),
            new Regex("^wank|^jerkoff|^motherf", Opts),
            // транслит: hui/huy/xuy, pizda, blyat, ebat, suka, pidor, mudak, zalupa, zhopa
            new Regex("^(?:na|po|ni|o|za)?(?:x|h|kh)u[iyj]", Opts),
            new Regex("p[ie]zd", Opts),
            new Regex("^bl(?:ya|ja|ia)", Opts),
            new Regex("^(?:za|vy|do|na|ot|raz|po|pro|u)?(?:e|yo|jo|io)b(?:at|al|an|lo|la|u$|nu|ish)", Opts),
            new Regex("^suka$|^suchk", Opts),
            new Regex("pid[oa]r|^pidr", Opts),
            new Regex("^mudak|zalup|^gandon|^gondon", Opts),
            new Regex("^(?:zh|j)op(?:a|y|u|e)?$|^zhop", Opts),
        };

        /// <summary>
        /// Нормальные слова, внутри которых есть совпадение с корнем ("подстрахуй",
        /// "скипидар"). Если найденное совпадение целиком лежит внутри такой подстроки
        /// — это не мат. Записаны в нормализованном виде (без ь, без двойных букв).
        /// </summary>
        public static readonly IReadOnlyList<string> Exceptions = new[]
        {
            "страху", "страхуй", "психу", "психуй",
            "скипидар",
            "бляха", "бляхи", "бляху", "бляхой", "бляш",
            "херувим",
            "ебонит",
        };

