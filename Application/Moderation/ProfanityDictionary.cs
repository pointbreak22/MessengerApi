using System.Collections.Generic;
using System.Text.RegularExpressions;

namespace Application.Moderation
{
    /// <summary>
    /// Словарь фильтра: корни мата и "ниже пояса", исключения и замены-подсказки.
    ///
    /// Все шаблоны применяются к уже нормализованному слову (см. ProfanityFilter):
    /// нижний регистр, ё→е, без ь, повторы букв схлопнуты в одну ("хууууй" → "хуй").
    /// Поэтому в шаблонах нет ё, ь и двойных букв — иначе они никогда не совпадут.
    ///
    /// Шаблоны намеренно не "ищут корень где угодно": голая подстрока ловит кучу
    /// нормальных слов ("бля" в "употребляя", "еб" в "хлеб", "манда" в "команда").
    /// Корни, которые часто встречаются внутри обычных слов, привязаны к началу
    /// слова и к известным приставкам, остальные — проверяются по списку исключений.
    /// </summary>
    internal static class ProfanityDictionary
    {
        private const RegexOptions Opts = RegexOptions.CultureInvariant | RegexOptions.Compiled;

        // Приставки, с которыми употребляется корень "еб". Согласные приставки,
        // совпадающие с началом обычных слов ("с"+"еб" = "себе", "в"+"еб" = "веб"),
        // требуют твёрдого знака — без него это просто другое слово.
        private const string EbPrefixes =
            "(?:за|вы|до|у|на|от|отъ|разъ|раз|изъ|из|въ|съ|подъ|под|надъ|объ|об|при|про|пере|недо|не|по|о|долбо|долба|мозго|пизда|пиздо|ни)?";

        /// <summary>Русские шаблоны (для слов на кириллице и "похожих" латинских букв).</summary>
        public static readonly IReadOnlyList<Regex> Cyrillic = new[]
        {
            // хуй, хуйня, нахуй, похую, охуеть, нихуя, хуёвый
            new Regex("ху[йяеию]", Opts),
            new Regex("^ху(?:ли|ле|ля)$", Opts),
            // пизда, пиздец, распиздяй, "пездец"
            new Regex("п[ие]зд", Opts),
            // ебать, заебал, уебок, долбоеб, разъебать, ебло, йобаный
            new Regex("^" + EbPrefixes + "(?:е|йо)б(?:а|у|е|и|л|н|о|ы|ош|ук|ыр|ись)", Opts),
            new Regex("(?:долбо|долба|мозго)еб", Opts),
            // бля, блять, блядь, блядина (начало слова — внутри "корабля"/"употребляя" нормально)
            new Regex("^бля", Opts),
            new Regex("бляд", Opts),
            // пидор, пидарас, пидр, педик, педераст
            new Regex("пид[оа]р|пидр", Opts),
            new Regex("^педик|педераст|педрил", Opts),
            // мудак, мудила, мудозвон (не "мудрый")
            new Regex("муд(?:ак|ил|оз|ач|ень|ня|охат)", Opts),
            new Regex("залуп", Opts),
            // манда — только как отдельное слово (не "команда", "мандарин", "мандат")
            new Regex("^манд(?:а|ы|е|у|ой|ою)$|^мандав|^мандят|^мандеж", Opts),
            new Regex("шлюх|шалав|^курв", Opts),
            new Regex("^с?сук(?:а|и|е|у|ой|ин|ины|ам|ами)$|^сучк|^сучар|^сучен", Opts),
            // хер, херня, нахер, похерить (не "херувим")
            new Regex("^(?:на|по|ни|за)?хер(?:$|н|ов|ач|ак|ом|ит|ил|а$|у$|е$)", Opts),
            new Regex("г[ао]ндон", Opts),
            new Regex("дроч", Opts),
            new Regex("жоп", Opts),
            new Regex("говн", Opts),
            // срать, засранец, обосрался (не "сравнить", "сражение")
            new Regex("сра(?:т|л[аиоу]?$|лс|ка|н|ч)", Opts),
            new Regex("^(?:за|об|обо|на|по|вы|у)?сыкл|^засал$|^обосал", Opts),
            new Regex("^(?:от|вы|за)?трах(?:а|н|ну|ал|ат|ае|ун)", Opts),
            // "сиськи" после удаления ь — "сиски"; привязка к началу, иначе "сосиски"
            new Regex("^сиск|^сисек|^сиси$", Opts),
            new Regex("порн", Opts),
            new Regex("минет|^отсос(?:и$|ал)", Opts),
            new Regex("мастурб|онанир|оргазм|эрекц|пенис|вагин|влагалищ|клитор|^куни(?:л|н)", Opts),
            new Regex("^анал(?:$|н|ом|у$)", Opts),
            new Regex("^секс(?!т)", Opts),
            new Regex("^шмар|^потаскух|^давалк", Opts),
        };

        /// <summary>Латиница: английский мат и русский мат транслитом.</summary>
        public static readonly IReadOnlyList<Regex> Latin = new[]
        {
            new Regex("fu+c+k|^fuk(?!u)|^fck|^phuck|^fuq", Opts),
            new Regex("^shit|shit$|bullshit", Opts),
            new Regex("bitch", Opts),
            new Regex("^cunt", Opts),
            new Regex("^dick(?:s|head|hole)?$", Opts),
            new Regex("^cock(?:s|sucker)?$", Opts),
            new Regex("puss(?:y|ies)", Opts),
