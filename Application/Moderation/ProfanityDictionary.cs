            "blyat", "suka", "pizda", "hui", "huy", "xuy",
        };

        /// <summary>
        /// Замена корня внутри слова, когда точной формы нет в WordReplacements:
        /// "похую" → "пофигу", "охуевший" → "офигевший".
        /// </summary>
        public static readonly IReadOnlyList<(Regex Pattern, string Replacement)> RootReplacements = new[]
        {
            (new Regex("хуй", Opts), "фиг"),
            // после "г" пишется а/у, а не я/ю: "нахуя" → "нафига", "похую" → "пофигу"
            (new Regex("хуя", Opts), "фига"),
            (new Regex("хую", Opts), "фигу"),
            (new Regex("ху([еи])", Opts), "фиг$1"),
            (new Regex("п[ие]здец", Opts), "капец"),
            (new Regex("хер", Opts), "фиг"),
            (new Regex("жоп", Opts), "поп"),
            (new Regex("бляд|блят|^бля", Opts), "блин"),
